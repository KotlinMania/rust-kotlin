#!/usr/bin/env python3
"""Synchronize commented `.yml` rule files into `BundledYamlRuleSources.kt` for all KMP targets."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
RULES_DIR = ROOT / "src/common/commonMain/resources/io/github/kotlinmania/rustkotlin/rules"
OUT_KT = ROOT / "src/common/commonMain/kotlin/io/github/kotlinmania/rustkotlin/BundledYamlRuleSources.kt"


def to_const_name(stem: str) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "_", stem).strip("_").upper()


def escape_for_kotlin_raw_string(text: str) -> str:
    if '"""' in text:
        raise ValueError("Triple-quote sequence '\"\"\"' is not supported inside bundled YAML")
    return text.replace("$", "${'$'}")


def main() -> None:
    yml_files = sorted(RULES_DIR.glob("*.yml"))
    if not yml_files:
        raise SystemExit(f"No .yml files found in {RULES_DIR}")

    lines: list[str] = [
        "package io.github.kotlinmania.rustkotlin",
        "",
        "// Generated from `src/common/commonMain/resources/io/github/kotlinmania/rustkotlin/rules/*.yml`",
        "// by `python3 tools/sync-yaml-rules.py`. Do not edit this file directly; edit the `.yml` files instead.",
        "internal object BundledYamlRuleSources {",
        "    val filesByName: Map<String, String> by lazy {",
        "        mapOf(",
    ]
    for yml in yml_files:
        const_name = to_const_name(yml.stem)
        lines.append(f'            "{yml.name}" to {const_name},')
    lines.append("        )")
    lines.append("    }")

    for yml in yml_files:
        const_name = to_const_name(yml.stem)
        raw = yml.read_text(encoding="utf-8")
        has_trailing_nl = raw.endswith("\n")
        core_text = raw[:-1] if has_trailing_nl else raw
        escaped = escape_for_kotlin_raw_string(core_text)
        suffix = ' + "\\n"' if has_trailing_nl else ""
        lines.append("")
        lines.append(f"    val {const_name}: String =")
        lines.append('        """')
        for raw_line in escaped.split("\n"):
            lines.append(f"        |{raw_line}")
        lines.append(f'        """.trimMargin(){suffix}')

    lines.append("}")
    lines.append("")
    OUT_KT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Synced {len(yml_files)} YAML rule catalogs -> {OUT_KT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
